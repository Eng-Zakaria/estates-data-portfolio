"""Generate the nightly Parquet-to-P01 export SQL from the point registry.

`sql/export_bms_trends.sql` is generated rather than hand-written because the
export is one column per BMS point: with 294 points a hand-maintained list
drifts from the registry immediately, and a missing column is a silent data
loss rather than an error. The generator takes the point list from
`src/point_registry.csv` (or the live `bms.points` table, via --from-db) and
`tests/test_export_sql.py` asserts the committed file matches.

    python src/export_sql.py --out sql/export_bms_trends.sql
"""

from __future__ import annotations

import argparse
from pathlib import Path

from validate import load_registry

REPO = Path(__file__).resolve().parent.parent
REGISTRY_CSV = Path(__file__).resolve().parent / "point_registry.csv"

HEADER = """\
-- Nightly export of P15 aggregates to the P01 `bms_trends` contract.
--
-- GENERATED by `python src/export_sql.py --out sql/export_bms_trends.sql`.
-- Do not edit by hand: the point list comes from src/point_registry.csv, and
-- tests/test_export_sql.py checks this file matches the registry.
--
-- Writes the same wide shape as src/export_bms_trends.py: `timestamp` plus one
-- column per point, ISO-8601 with offset, "N/A" where the hour has no reading.
--
--   docker compose exec -T timescaledb \\
--     psql -U bms_user -d bms_db -v ON_ERROR_STOP=1 \\
--     -f /sql/export_bms_trends.sql
--   docker compose exec timescaledb cat /tmp/bms_trends.csv > data/raw/bms_trends_$(date +%Y%m%d).csv

\\copy (
{bucket_grid}
SELECT
    to_char(
        b.bucket AT TIME ZONE 'UTC' AT TIME ZONE 'Europe/London',
        'YYYY-MM-DD"T"HH24:MI:SSOF'
    ) AS "timestamp",
{columns}
FROM buckets b
ORDER BY b.bucket
) TO '/tmp/bms_trends.csv' WITH (FORMAT csv, HEADER true);
"""

BUCKETS = """\
WITH buckets AS (
    SELECT generate_series(
               date_trunc('hour', now() - INTERVAL '24 hours'),
               date_trunc('hour', now()) - INTERVAL '1 hour',
               INTERVAL '1 hour'
           ) AS bucket
),"""

COLUMN_TEMPLATE = """\
    coalesce(
        (SELECT r.avg_value::text
           FROM bms.readings_hourly r
          WHERE r.point_id = '{point_id}'
            AND r.bucket = b.bucket),
        'N/A'
    ) AS "{point_id} [{unit}]\""""


def build_sql(points: list[str] | None = None, registry_csv: Path = REGISTRY_CSV) -> str:
    """Return the export SQL for every point in the registry."""
    registry = load_registry(str(registry_csv))
    ids = points or sorted(registry)
    unknown = [pid for pid in ids if pid not in registry]
    if unknown:
        raise KeyError(f"points not in the registry: {unknown}")
    columns = ",\n".join(COLUMN_TEMPLATE.format(point_id=pid, unit=registry[pid]["unit"]) for pid in ids)
    return HEADER.format(bucket_grid=BUCKETS, columns=columns)


def write_sql(out: Path, points: list[str] | None = None) -> Path:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(build_sql(points), encoding="utf-8", newline="\n")
    return out


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=REPO / "sql" / "export_bms_trends.sql")
    parser.add_argument("--points", nargs="*", default=None)
    args = parser.parse_args()
    path = write_sql(args.out, args.points)
    print(f"Wrote {path} ({len(args.points) if args.points else 'all registry'} point columns)")


if __name__ == "__main__":
    main()