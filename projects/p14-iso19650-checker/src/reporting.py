def rules_table(result: CheckResult) -> list[tuple[str, str, int, str]]:
    counts: dict[str, list[str]] = defaultdict(list)
    severity: dict[str, str] = {}
    for issue in result.issues:
        counts[issue.rule_id].append(issue.message)
        severity.setdefault(issue.rule_id, issue.severity)
    return [(rule, severity[rule], len(messages), messages[0]) for rule, messages in sorted(counts.items())]


def render_text(result: CheckResult, summary: list[dict[str, str]], renames: list[tuple[str, str]]) -> str:
    lines = [
        f"Convention: {result.convention}",
        f"Root:       {result.root}",
        f"Files:      {result.total_files}",
        f"Compliance: {result.compliance_pct():.1f}% compliant "
        f"({result.error_count} errors, {result.warning_count} warnings in "
        f"{result.files_with_errors} files)",
        "",
        "Findings by rule:",
    ]
    if result.issues:
        width_rule = max(len(r) for r, _, _, _ in rules_table(result))
        for rule, severity, count, _example in rules_table(result):
            lines.append(f"  {rule:<{width_rule}}  {count:>5}  {severity}")
    else:
        lines.append("  (none)")
    lines += ["", "Compliance summary (by field / folder / originator):"]
    for row in summary:
        lines.append(
            f"  {row['dimension']:<11} {row['key']:<12} files={row['files']:>5} "
            f"errors={row['errors']:>5} warnings={row['warnings']:>5} compliance={row['compliance_pct']:>5}%"
        )
    if renames:
        lines += ["", f"Suggested renames ({len(renames)}, case/separator fixes only; nothing renamed):"]
        lines += [f"  {old}  ->  {new}" for old, new in renames[:20]]
        if len(renames) > 20:
            lines.append(f"  ... and {len(renames) - 20} more")
    if result.skipped_checks:
        lines += ["", f"Skipped checks: {', '.join(result.skipped_checks)}"]
    return "\n".join(lines)


def render_html(
    result: CheckResult,
    summary: list[dict[str, str]],
    renames: list[tuple[str, str]],
    convention_name: str,
    description: str,
    source: str,
    retrieved: str,
) -> str:
    env = Environment(autoescape=select_autoescape(["html", "xml"]))
    return env.from_string(TEMPLATE).render(
        convention=convention_name,
        description=description,
        source=source,
        retrieved=retrieved,
        compliance=result.compliance_pct(),
        total_files=result.total_files,
        errors=result.error_count,
        warnings=result.warning_count,
        rules=rules_table(result),
        summary=summary,
        issues=result.issues,
        renames=renames,
        skipped=result.skipped_checks,
    )


def render_json(result: CheckResult, summary: list[dict[str, str]], renames: list[tuple[str, str]]) -> str:
    payload = json.loads(result.to_json())
    payload["summary"] = summary
    payload["suggested_renames"] = [{"from": o, "to": n} for o, n in renames]
    return json.dumps(payload, indent=2)


def render_junit(result: CheckResult, out: Path, fail_on: str = ERROR) -> Path:
    """JUnit XML so a CI job fails on convention violations.

    One testcase per rule that fired; a rule that did not fire is reported as a passing testcase, so a
    clean run is visibly green rather than an empty report.
    """
    by_rule: dict[str, list] = defaultdict(list)
    for issue in result.issues:
        by_rule[issue.rule_id].append(issue)
    root = ET.Element("testsuites", name="iso19650-convention-check")
    suite = ET.SubElement(
        root,
        "testsuite",
        name=f"iso19650:{result.convention}",
        tests=str(len(by_rule) or 1),
        failures=str(sum(1 for i in result.issues if i.severity == ERROR)),
        skipped=str(len(result.skipped_checks)),
        time="0",
    )
    if not by_rule:
        ET.SubElement(suite, "testcase", classname="iso19650", name="no violations found")
    for rule, issues in sorted(by_rule.items()):
        case = ET.SubElement(
            suite,
            "testcase",
            classname="iso19650",
            name=f"{rule} ({len(issues)})",
            file=issues[0].path,
        )
        blocking = [i for i in issues if i.severity == ERROR]
        if blocking and (fail_on == ERROR or fail_on == "any"):
            failure = ET.SubElement(case, "failure", message=f"{rule}: {len(blocking)} error(s)")
            failure.text = "\n".join(f"{i.path}: {i.message}" for i in blocking)
        elif any(i.severity == ERROR for i in issues):
            ET.SubElement(suite, "skipped", message=f"{rule}: errors present but fail-on={fail_on}")
    out.parent.mkdir(parents=True, exist_ok=True)
    ET.ElementTree(root).write(out, encoding="utf-8", xml_declaration=True)
    return out
