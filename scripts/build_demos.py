"""Build the static, interactive demo pages published to GitHub Pages.

Usage:
    python scripts/build_demos.py [--out docs/apps] [--only p06 dbt-marts]

Reads the same gold marts, DuckDB stores and project outputs the READMEs quote,
writes one self-contained HTML file per project into --out, plus an index page.
Every figure is the measured value; nothing is invented. Missing inputs produce a
page that says so rather than empty charts.
"""

from __future__ import annotations

import argparse
import importlib
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from scripts.demos import catalogue  # noqa: E402
from scripts.demos.base import note, page  # noqa: E402

MODULES = [
    "scripts.demos.pages_platform",
    "scripts.demos.pages_dashboards",
    "scripts.demos.pages_bim",
    "scripts.demos.pages_analytics",
]

# page slug -> "module:function"
BUILDERS: dict[str, str] = {
    "foundation": "pages_platform:foundation",
    "lakehouse": "pages_platform:lakehouse",
    "orchestration": "pages_platform:orchestration",
    "data-quality": "pages_platform:data_quality",
    "dbt-marts": "pages_platform:dbt_marts",
    "cicd": "pages_platform:cicd",
}


def collect() -> dict[str, tuple]:
    """Import every builder module and gather slug -> (id, picker, title, sub, body, js).

    Each module exposes a ``PAGES`` dict of {slug: builder}. A builder returns
    (picker, title, subtitle, body_html, extra_js).
    """
    pages: dict[str, tuple] = {}
    for mod_name in MODULES:
        try:
            mod = importlib.import_module(mod_name)
        except ModuleNotFoundError as exc:
            if exc.name == mod_name:
                print(f"  (skipping missing module {mod_name})")
                continue  # module not written yet
            raise
        for slug, builder in getattr(mod, "PAGES", {}).items():
            result = list(builder())
            extra_head = result[5] if len(result) > 5 else ""
            pages[slug] = (getattr(builder, "project_id", slug), *result[:5], extra_head)
    return pages


def index_html(pages: dict[str, tuple]) -> str:
    nav = catalogue.picker()
    cards = []
    for pid, label, slug, blurb, has_demo in catalogue.PROJECTS:
        if has_demo and slug in pages:
            link = f'<a class="card" style="text-decoration:none;display:block" href="{slug}.html">'
            inner = (
                f'{link}<div class="eyebrow">{pid}</div>'
                f'<h3 style="margin:6px 0 8px;color:#e8eef4;font-size:16px;text-transform:none;'
                f'letter-spacing:0">{label.split(" · ", 1)[-1]}</h3>'
                f'<div class="sub">{blurb}</div>'
                f'<div class="n" style="color:#57d9a3;margin-top:10px;font-size:12px">Interactive demo →</div></a>'
            )
        else:
            inner = (
                f'<div class="card"><div class="eyebrow">{pid}</div>'
                f'<h3 style="margin:6px 0 8px;color:#e8eef4;font-size:16px;text-transform:none;'
                f'letter-spacing:0">{label.split(" · ", 1)[-1]}</h3>'
                f'<div class="sub">{blurb}</div></div>'
            )
        cards.append(f'<div class="card">{inner}</div>')
    body = (
        note(
            "Twenty projects covering data pipelines, orchestration, data quality, dbt modelling, "
            "Power BI handoff, BIM and standards, building systems, spatial analysis, a digital-twin "
            "data layer, and governance. "
            "<strong>All data is synthetic</strong> — generated by the portfolio's own generator with "
            "a known ground truth, so the numbers here are reproducible and testable."
        )
        + '<div class="grid g3">' + "".join(cards) + "</div>"
    )
    return page(
        project_id="index",
        title="Estates Data Portfolio",
        subtitle="Data pipelines, dbt marts, data quality, Power BI handoff, BIM/standards, "
                 "building systems and governance for a university estates function.",
        body=body,
        picker=nav,
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default="docs/apps", help="output directory for HTML pages")
    parser.add_argument("--only", nargs="*", default=None, help="build only these page slugs")
    args = parser.parse_args()

    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)

    pages = collect()
    # Pickers reference every project, so make sure unknown slugs still resolve to the index.
    for _pid, _label, slug, _blurb, _has in catalogue.PROJECTS:
        if slug not in pages:
            pages[slug] = (
                _pid,
                catalogue.picker(),
                f"{_label.split(' · ', 1)[-1]} — no demo yet",
                "This project's evidence lives in the repository rather than a browser demo.",
                '<div class="note">Demo not built. See the project README and acceptance doc in the repo.</div>',
                "",
            )

    written = 0
    for slug, entry in sorted(pages.items()):
        pid, nav, title, sub, body_html, extra_js = entry[:6]
        extra_head = entry[6] if len(entry) > 6 else ""
        if args.only and slug not in args.only:
            continue
        html = page(
            project_id=pid,
            title=title,
            subtitle=sub,
            body=body_html,
            picker=nav,
            extra_js=extra_js,
            extra_head=extra_head,
        )
        (out_dir / f"{slug}.html").write_text(html, encoding="utf-8")
        written += 1
        print(f"  wrote {out_dir / (slug + '.html')}")

    if not args.only:
        (out_dir / "index.html").write_text(index_html(pages), encoding="utf-8")
        print(f"  wrote {out_dir / 'index.html'}")
        written += 1

    print(f"{written} page(s) written to {out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())